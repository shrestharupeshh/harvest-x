"""Integrated harvest simulation: perception -> decision -> state machine (SIMULATED).

Question (RQ-D, simulation level): how do the target source, the stem-seated sensor and
the mechanical capture width of the fork trade off against each other?

Every strategy attempts the same plants (those the maturity model calls harvest-ready
with P >= 0.6), so differences come from localisation and gating only. Cutting physics
and damage are not simulated: a seated, armed cut counts as a harvest.

    python -m harvestx_harvest.study
"""

from __future__ import annotations

import argparse
import json
import subprocess
from collections import Counter
from dataclasses import replace
from pathlib import Path

import numpy as np

from harvestx_perception import benchmark as B
from harvestx_perception.pipeline import PipelineConfig
from harvestx_perception.synthetic.scene import SceneConfig

from .machine import HarvestConfig, HarvestMachine, Outcome, SimGantry, SimTool

ROOT = Path(__file__).resolve().parents[2]
STRATEGIES = {
    # name: (stem candidate used as target, sensor gate, seat attempts)
    "vision only (RGB-D centroid), open loop": ("centroid_3d", False, 1),
    "fixture prior, open loop": ("site_prior", False, 1),
    "fusion, open loop": ("fusion", False, 1),
    "fusion + stem sensor, no retry": ("fusion", True, 1),
    "fusion + stem sensor + lateral retry": ("fusion", True, 3),
}
HALF_WIDTHS_MM = (5, 10, 15, 25)


def run(n_trays: int = 150, seed: int = 20261116) -> dict:
    scfg = SceneConfig(age_range_days=(26.0, 40.0))  # trays near harvest: more attempts
    samples = B.generate(scfg, n_trays, 1, seed)
    split = B.split_trays([s.meta["tray_id"] for s in samples], seed)
    rows = B.collect_rows(samples, split, PipelineConfig())
    sigma = B.calibrate_sigma([r for r in rows if r["split"] == "train"])
    _, model, _, _ = B.eval_maturity(rows)
    cfg = PipelineConfig(sigma_scale=sigma)

    attempts = []  # (plant truth, observation, channel_y, plane_z)
    n_ready = 0
    for s in (x for x in samples if split[x.meta["tray_id"]] == "test"):
        truth = {p.site_index: p for p in s.plants}
        n_ready += sum(p.maturity == "harvest_ready" for p in s.plants)
        sites = s.rack.sites()
        for o in B.run(s, cfg, model).observations:
            p = truth.get(o.site_index)
            if p is None or o.maturity_probs is None:
                continue
            if o.maturity == "harvest_ready" and o.maturity_probs["harvest_ready"] >= 0.6:
                attempts.append((p, o, float(sites[o.site_index][1]), s.rack.plane_z))

    table = {}
    for hw in HALF_WIDTHS_MM:
        for name, (cand, gate, tries) in STRATEGIES.items():
            hc = HarvestConfig(usable_half_width=hw / 1000, sensor_gate=gate,
                               max_seat_attempts=tries, cut_armed=True)
            outcomes, times, seats = Counter(), [], []
            for p, o, ch_y, pz in attempts:
                if cand not in o.stem_candidates:
                    outcomes["NO_TARGET"] += 1
                    continue
                m = HarvestMachine(hc, SimGantry(hc), SimTool(hc))
                rec = m.harvest(p.plant_id, o.stem_candidates[cand], np.array(p.cut_target), ch_y, pz)
                outcomes[rec.outcome.value] += 1
                seats.append(rec.seat_attempts)
                if rec.outcome is Outcome.HARVESTED:
                    times.append(rec.duration_s)
            n = len(attempts)
            table[f"{hw}|{name}"] = dict(
                half_width_mm=hw, strategy=name, attempts=n, outcomes=dict(outcomes),
                harvested=outcomes["HARVESTED"] / n, blind_cut=outcomes["BLIND_CUT"] / n,
                missed=outcomes["MISSED"] / n, mean_seat_attempts=float(np.mean(seats)),
                mean_cycle_s=float(np.mean(times)) if times else float("nan"))
    truly = sum(p.maturity == "harvest_ready" for p, *_ in attempts)
    try:
        git = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True,
                             text=True, check=True).stdout.strip()
    except Exception:
        git = "unknown"
    return dict(data_kind="SIMULATED", git=git, seed=seed, n_trays=n_trays,
                n_test_trays=sum(v == "test" for v in split.values()), attempts=len(attempts),
                attempts_truly_ready=truly, ready_plants_in_test=n_ready, table=table,
                harvest_config=replace(HarvestConfig(), cut_armed=True).__dict__ | {"limits": None})


def to_markdown(r: dict) -> str:
    L = ["<!-- GENERATED by `python -m harvestx_harvest.study` - do not edit by hand -->",
         "# Integrated harvest simulation v0 — SIMULATED", "",
         "> Perception (synthetic images) -> maturity decision -> harvest state machine with a "
         "kinematic gantry and a geometric fork-capture model. **Cutting and plant damage are "
         "not simulated**; a seated, armed cut counts as harvested. Numbers describe the "
         "simulator, not a robot.", "",
         f"- Commit `{r['git']}`, seed {r['seed']}, {r['n_trays']} near-harvest trays, "
         f"{r['n_test_trays']} held-out test trays",
         f"- Harvest attempts (plants predicted harvest-ready with P >= 0.6): {r['attempts']}; of "
         f"these truly harvest-ready: {r['attempts_truly_ready']} "
         f"({r['attempts_truly_ready'] / max(r['attempts'], 1):.0%}); harvest-ready plants "
         f"present in the test trays: {r['ready_plants_in_test']}",
         "- The same plants are attempted under every strategy, so the table isolates "
         "localisation, gating and capture width. Maturity errors are identical across rows.", ""]
    for hw in HALF_WIDTHS_MM:
        L += [f"## Usable capture half-width {hw} mm", "",
              "| strategy | harvested | blind cut (blade fired, no stem) | missed (no cut) | "
              "mean seat attempts | mean cycle [s] |", "|---|---|---|---|---|---|"]
        for name in STRATEGIES:
            v = r["table"][f"{hw}|{name}"]
            L.append(f"| {name} | {v['harvested']:.1%} | {v['blind_cut']:.1%} | {v['missed']:.1%} | "
                     f"{v['mean_seat_attempts']:.2f} | {v['mean_cycle_s']:.1f} |")
        L.append("")
    L += ["## Reading", "",
          "- A blind cut is the failure that matters: the blade closes on leaves or on nothing. "
          "The stem-seated sensor converts every blind cut into a harmless miss by construction; "
          "what the simulation adds is how often that happens and what a retry recovers.",
          "- Capture width and target accuracy substitute for each other. The selected fork "
          "(25 mm usable half-width) is the row to compare with narrower, blade-only tools.",
          "- Cycle times come from motion limits and fixed allowances.", ""]
    return "\n".join(L)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=ROOT / "simulation/results/harvest_sim_v0")
    ap.add_argument("--trays", type=int, default=150)
    a = ap.parse_args(argv)
    r = run(a.trays)
    a.out.mkdir(parents=True, exist_ok=True)
    (a.out / "results.json").write_text(json.dumps(r, indent=2, default=str))
    (a.out / "REPORT.md").write_text(to_markdown(r))
    print(to_markdown(r))


if __name__ == "__main__":
    main()
