"""Geometric leaf-interference study for tool approach strategies (SIMULATED).

Uses the same rosette leaf model as the perception simulator. For each strategy the
volume swept by the tool is described by axis-aligned boxes in a frame centred on the
target stem (x along the channel, y across it with the tool arriving from -y, z up
from the channel surface). The metric is the fraction of leaf area lying inside the
swept volume, i.e. leaf area the tool would have to push aside.

Leaves are treated as rigid and fixed, so this is an upper bound on *contact*, and it
says nothing about damage: real leaves bend out of the way. It is a design-ranking
aid, not a prediction.

    python -m harvestx_mech.approach_study
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

from harvestx_perception.synthetic.growth import sample_plant
from harvestx_perception.synthetic.scene import _plant_leaves

ROOT = Path(__file__).resolve().parents[2]
BIG = 1.0  # "infinite" extent [m]


def strategies(p: dict) -> dict[str, list[tuple]]:
    """Boxes (xmin, xmax, ymin, ymax, zmin, zmax) in metres for each strategy."""
    ee = p["end_effector"]
    hw = ee["plate_width_m"] / 2
    tip, back = ee["tine_length_m"], 0.06
    head_h = ee["skid_thickness_m"] + ee["plate_thickness_m"] + 0.014  # incl. camera
    boom_hw = ee["boom_width_m"] / 2
    return {
        "S1 top-down onto the stem (compact tool, vertical shank)": [
            (-hw, hw, -back - 0.04, tip, 0.0, BIG)],
        "S2 descend through canopy beside the stem, short slide": [
            (-hw, hw, -back - tip - 0.045, -0.015, 0.0, BIG),      # descent column
            (-hw, hw, -back - tip - 0.045, tip, 0.0, 0.06)],       # slide incl. actuator on head
        "S3 side entry under canopy (low-profile head on boom)": [
            (-hw, hw, -back, tip, 0.0, head_h),                    # head at the seated position
            (-hw, hw, -BIG, -back, 0.0, head_h),                   # path swept by the head
            (-boom_hw, boom_hw, -back - ee["boom_length_m"], -back, 0.0, head_h),
            (-0.03, 0.03, -BIG, -back - ee["boom_length_m"] + 0.06, 0.0, BIG)],  # shank + actuator
    }


def leaf_samples(leaves, n_per_leaf: int, rng) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Uniform samples on each leaf. Returns (points Nx3, area weight N, inner-leaf flag N)."""
    pts, w, inner = [], [], []
    for lf in leaves:
        rho, th = np.sqrt(rng.random(n_per_leaf)), rng.uniform(0, 2 * np.pi, n_per_leaf)
        q = (lf["C"][None] + (lf["a"] * rho * np.cos(th))[:, None] * lf["u"][None]
             + (lf["b"] * rho * np.sin(th))[:, None] * lf["v"][None])
        pts.append(q)
        w.append(np.full(n_per_leaf, lf["a"] * lf["b"] / n_per_leaf))
        inner.append(np.full(n_per_leaf, lf["f"] > 0.5))
    return np.concatenate(pts), np.concatenate(w), np.concatenate(inner)


def inside(pts: np.ndarray, boxes: list[tuple]) -> np.ndarray:
    m = np.zeros(len(pts), bool)
    for x0, x1, y0, y1, z0, z1 in boxes:
        m |= ((pts[:, 0] >= x0) & (pts[:, 0] <= x1) & (pts[:, 1] >= y0) & (pts[:, 1] <= y1)
              & (pts[:, 2] >= z0) & (pts[:, 2] <= z1))
    return m


def run(p: dict, n_plants: int = 300, seed: int = 0, age: float = 34.0) -> dict:
    rng = np.random.default_rng(seed)
    strat = strategies(p)
    pitch = p["rack"]["pitch_along_m"]
    acc = {k: dict(target=[], target_inner=[], neighbours=[]) for k in strat}
    for _ in range(n_plants):
        sets = []
        for dx in (0.0, -pitch, pitch):  # target and its two neighbours in the same channel
            st = sample_plant(rng, "butterhead", age + rng.normal(0, 1.5))
            leaves = _plant_leaves(rng, st, np.array([dx, 0.0, 0.0]), 0.35)
            sets.append(leaf_samples(leaves, 60, rng))
        for name, boxes in strat.items():
            pts, w, inner = sets[0]
            hit = inside(pts, boxes)
            acc[name]["target"].append(w[hit].sum() / w.sum())
            acc[name]["target_inner"].append(w[hit & inner].sum() / max(w[inner].sum(), 1e-12))
            nb = [wn[inside(pn, boxes)].sum() / wn.sum() for pn, wn, _ in sets[1:]]
            acc[name]["neighbours"].append(float(np.mean(nb)))
    out = {}
    for name, a in acc.items():
        out[name] = {k: dict(mean=float(np.mean(v)), p95=float(np.percentile(v, 95)))
                     for k, v in a.items()}
    return dict(data_kind="SIMULATED", n_plants=n_plants, seed=seed, age_days=age, results=out)


def to_markdown(res: dict) -> str:
    L = ["<!-- GENERATED by `python -m harvestx_mech.approach_study` - do not edit by hand -->",
         "# Approach-direction leaf-interference study (SIMULATED)", "",
         "> Rigid, fixed leaves from the procedural rosette model; butterhead near harvest "
         f"({res['n_plants']} sampled plants with two same-channel neighbours each, seed "
         f"{res['seed']}). The metric is the share of leaf area inside the volume swept by the "
         "tool. It is an upper bound on contact and **not** a damage prediction.", "",
         "| strategy | target plant: leaf area in tool path (mean / p95) | target inner leaves "
         "(heart) | neighbouring plants |", "|---|---|---|---|"]
    for name, r in res["results"].items():
        L.append(f"| {name} | {r['target']['mean']:.1%} / {r['target']['p95']:.1%} | "
                 f"{r['target_inner']['mean']:.1%} / {r['target_inner']['p95']:.1%} | "
                 f"{r['neighbours']['mean']:.1%} / {r['neighbours']['p95']:.1%} |")
    L += ["", "Reading: with side entry the tool path contains only low outer leaves and "
          "essentially none of the heart, whereas descending through the canopy, at the stem or "
          "beside it, puts most of the leaf area, including the heart, in the tool's way. The "
          "conclusion rests on the assumed leaf geometry (flat elliptical leaves, assumed "
          "elevation angles) and must be re-checked against scans or photographs of real "
          "plants.", ""]
    return "\n".join(L)


def main(argv=None):
    from .params import load_params

    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=ROOT / "docs/mechanical")
    a = ap.parse_args(argv)
    res = run(load_params())
    a.out.mkdir(parents=True, exist_ok=True)
    (a.out / "approach_study.json").write_text(json.dumps(res, indent=2))
    (a.out / "approach_study.md").write_text(to_markdown(res))
    print(to_markdown(res))


if __name__ == "__main__":
    main()
