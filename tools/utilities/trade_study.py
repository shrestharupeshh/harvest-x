#!/usr/bin/env python3
"""Weighted decision matrix with Monte-Carlo sensitivity analysis.

Reads a YAML file (architectures, criteria scores, weight profiles) and writes a
Markdown report. The sensitivity analysis answers: "how often does each option rank
first if my weights and scores are somewhat wrong?"

    python tools/utilities/trade_study.py docs/architecture/trade_study.yaml \
        -o docs/architecture/trade_study_results.md
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import yaml


def weighted_scores(scores: np.ndarray, weights: np.ndarray) -> np.ndarray:
    """scores: (n_criteria, n_options); weights: (n_criteria,). Returns (n_options,)."""
    w = np.asarray(weights, float)
    return (w / w.sum()) @ np.asarray(scores, float)


def sensitivity(scores: np.ndarray, weights: np.ndarray, n: int = 20000, weight_rel: float = 0.5,
                score_abs: float = 1.0, seed: int = 0) -> np.ndarray:
    """Fraction of trials in which each option ranks first.

    Each trial multiplies every weight by U(1-weight_rel, 1+weight_rel) and adds
    U(-score_abs, +score_abs) to every score (clipped to 1..5).
    """
    rng = np.random.default_rng(seed)
    s = np.asarray(scores, float)
    wins = np.zeros(s.shape[1])
    for _ in range(n):
        w = np.asarray(weights, float) * rng.uniform(1 - weight_rel, 1 + weight_rel, len(weights))
        sp = np.clip(s + rng.uniform(-score_abs, score_abs, s.shape), 1, 5)
        wins[np.argmax(weighted_scores(sp, w))] += 1
    return wins / n


def build_report(cfg: dict) -> str:
    keys = list(cfg["architectures"])
    crit = list(cfg["criteria"])
    S = np.array([cfg["criteria"][c] for c in crit], float)
    out = ["<!-- GENERATED by tools/utilities/trade_study.py - do not edit by hand -->",
           "# Architecture trade study: computed results", "",
           "Scores are engineering judgement (1-5, 5 = best), not measurements.", "",
           "## Scores", "", "| criterion | " + " | ".join(k.split("_")[0] for k in keys) + " |",
           "|---|" + "---|" * len(keys)]
    out += [f"| {c} | " + " | ".join(f"{v:g}" for v in S[i]) + " |" for i, c in enumerate(crit)]
    for prof, wd in cfg["profiles"].items():
        w = np.array([wd[c] for c in crit], float)
        tot, win = weighted_scores(S, w), sensitivity(S, w)
        out += ["", f"## Profile: {prof}", "",
                "| option | weighted score (1-5) | rank | ranks first under perturbation |",
                "|---|---|---|---|"]
        order = np.argsort(-tot)
        for rank, i in enumerate(order, 1):
            out.append(f"| {cfg['architectures'][keys[i]]} | {tot[i]:.2f} | {rank} | {win[i]:.0%} |")
        out += ["", "Weights: " + ", ".join(f"{c} {x / w.sum():.0%}" for c, x in zip(crit, w))]
    out += ["", "Perturbation model: each weight x U(0.5, 1.5), each score + U(-1, +1) clipped "
            "to 1-5, 20 000 trials, fixed seed.", ""]
    return "\n".join(out)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("config", type=Path)
    ap.add_argument("-o", "--out", type=Path)
    a = ap.parse_args(argv)
    report = build_report(yaml.safe_load(a.config.read_text()))
    if a.out:
        a.out.write_text(report)
    else:
        print(report)


if __name__ == "__main__":
    main()
